"""`azalabscode` -- an owned, extensible async agentic harness.

Four layers, each replaceable without touching the others:

    tui  ->  control  ->  workflows  ->  providers | tools
                                              |
                                          contracts
                                              |
        events -> messages -> permissions -> toolio -> content -> leaves

Everything re-exported here, plus everything in a layer's own `__init__`, is the
public API (R-X-6). Reference workflows import from these two places and nowhere
else; import-linter enforces it.

`azalabscode.tui` is deliberately *not* re-exported here, so that importing the
harness does not import Textual. Import it directly when you need it.
"""

